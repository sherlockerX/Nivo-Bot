    /** 仅精确匹配内置原始行，名称或编号相同不代表同一份教学内容。 */
    fun unitIds(courseId: String): List<String> = units.keys.filter { it.startsWith("$courseId:") }
        .map { it.substringAfter(':') }

    /** 原始行摘要不一致时拒绝复用侧车，保留用户自己的内容。 */
    fun target(courseId: String, unitId: String, source: String): Target? {
        val entry = units["$courseId:$unitId"] ?: return null
        val hash = MessageDigest.getInstance("SHA-256").digest(source.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it.toInt() and 0xff) }
        return entry.target.takeIf { entry.sourceHash == hash }
    }
